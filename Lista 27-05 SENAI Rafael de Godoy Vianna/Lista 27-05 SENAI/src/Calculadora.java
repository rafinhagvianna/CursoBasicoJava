public class Calculadora {
    public  static String soma(int a, int b) {
        return a + " + " + b + " = " + (a + b);
    }
    public  static String subtracao(int a, int b) {
        return a + " - " + b + " = " + (a - b);
    }
    public  static String multiplicacao(int a, int b) {
        return a + " * " + b + " = " + (a * b);
    }
    public  static String divisao(int a, int b) {
        return a + " / " + b + " = " + (a / b);
    }

}
